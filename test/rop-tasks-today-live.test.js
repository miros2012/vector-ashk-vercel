import assert from 'node:assert/strict';
import { buildRopTasksToday } from '../lib/rop-tasks-today.js';

const VALUES = [
  ['Срез','Дата отчёта','Уровень','Менеджер','Филиал','План месяца','План к дате','Факт дня','Факт с начала месяца','Выполнение','Дефицит к плану на дату','Прогноз месяца','Отклонение прогноза','Контрольный план менеджера','Личный факт дня','Личный факт с начала месяца','Новых договоров','100% оплат новых договоров','Текущая ДЗ','Приоритет','Задача старшей','Примечание'],
  ['ВЧЕРА — ЗАКРЫТО','2026-09-01','МЕНЕДЖЕР','Менеджер А','Зарека',1110000,40259.07,10000,10000,0.248,30259.07,275000,-835000,1110000,10000,10000,0,0,655450,'СЕГОДНЯ','Вчера добрать 30 259 ₽',''],
  ['СЕГОДНЯ — НА СЕЙЧАС','2026-09-02','МЕНЕДЖЕР','Менеджер А','Зарека',1110000,97772.02,70000,80000,0.818,17772.02,908240,-201760,1110000,70000,80000,1,1,640000,'СЕГОДНЯ','Сегодня добрать 17 772 ₽','']
];

test('tasks today uses live today snapshot when it is available', () => {
  const result = buildRopTasksToday({ morningValues: VALUES, taskDate: '2026-09-02' });
  const headers = result.values[0];
  const idx = name => headers.indexOf(name);
  const row = result.values[1];
  assert.equal(result.reportDate, '2026-09-02');
  assert.equal(row[idx('Дата отчёта')], '2026-09-02');
  assert.equal(row[idx('Факт сегодня')], 70000);
  assert.equal(row[idx('Факт с начала месяца')], 80000);
  assert.equal(row[idx('Дефицит, ₽')], 17772.02);
  assert.match(row[idx('Задача')], /17.?772/);
});
